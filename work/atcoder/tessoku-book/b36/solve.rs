#[allow(unused_macros)]
macro_rules! debug {
    ($($a:expr),* $(,)*) => {
        #[cfg(debug_assertions)]
        eprintln!(concat!($("| ", stringify!($a), "={:?} "),*, "|"), $(&$a),*);
    };
}

#[fastout]
fn main() {
    input! {
        _n: usize, k: usize,
        s: Chars,
    }

    let ans = k.abs_diff(s.iter().counts().get(&'1').copied().unwrap_or(0)) % 2 == 0;

    println!("{}", if ans { "Yes" } else { "No" });
}
