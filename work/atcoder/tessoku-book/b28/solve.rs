#[allow(unused_macros)]
macro_rules! debug {
    ($($a:expr),* $(,)*) => {
        #[cfg(debug_assertions)]
        eprintln!(concat!($("| ", stringify!($a), "={:?} "),*, "|"), $(&$a),*);
    };
}

#[fastout]
fn main() {
    input! {
        n: usize,
    }

    use ac_library::ModInt1000000007 as Mint;

    let mut a1 = Mint::new(1);
    let mut a2 = Mint::new(1);

    for _ in 3..=n {
        let a = a1 + a2;
        a2 = a1;
        a1 = a;
    }

    println!("{}", a1);
}
