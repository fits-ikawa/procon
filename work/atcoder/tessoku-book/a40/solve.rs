#[allow(unused_macros)]
macro_rules! debug {
    ($($a:expr),* $(,)*) => {
        #[cfg(debug_assertions)]
        eprintln!(concat!($("| ", stringify!($a), "={:?} "),*, "|"), $(&$a),*);
    };
}

#[fastout]
fn main() {
    input! {
        n: usize,
        a: [usize; n],
    }

    let ans = a
        .into_iter()
        .counts()
        .values()
        .map(|&v| if v >= 3 { v * (v - 1) * (v - 2) / 6 } else { 0 })
        .sum::<usize>();

    println!("{}", ans);
}
