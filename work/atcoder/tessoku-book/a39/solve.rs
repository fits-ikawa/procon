#[allow(unused_macros)]
macro_rules! debug {
    ($($a:expr),* $(,)*) => {
        #[cfg(debug_assertions)]
        eprintln!(concat!($("| ", stringify!($a), "={:?} "),*, "|"), $(&$a),*);
    };
}

#[fastout]
fn main() {
    input! {
        n: usize,
        mut lr: [(usize, usize); n],
    }

    lr.sort_by_key(|&(_, r)| r);

    let mut cur = 0;
    let mut ans = 0;

    for (l, r) in lr {
        if cur <= l {
            ans += 1;
            cur = r;
        }
    }

    println!("{}", ans);
}
