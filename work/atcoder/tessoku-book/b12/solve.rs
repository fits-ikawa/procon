#[allow(unused_macros)]
macro_rules! debug {
    ($($a:expr),* $(,)*) => {
        #[cfg(debug_assertions)]
        eprintln!(concat!($("| ", stringify!($a), "={:?} "),*, "|"), $(&$a),*);
    };
}

#[fastout]
fn main() {
    input! {
        n: usize,
    }

    let mut left = 0.0;
    let mut right = n as f64;

    while (right - left) > 0.000001 {
        let mid = (left + right) / 2.0;

        if mid * mid * mid + mid >= n as f64 {
            right = mid;
        } else {
            left = mid;
        }
    }

    println!("{}", right);
}
