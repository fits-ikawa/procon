#[allow(unused_macros)]
macro_rules! debug {
    ($($a:expr),* $(,)*) => {
        #[cfg(debug_assertions)]
        eprintln!(concat!($("| ", stringify!($a), "={:?} "),*, "|"), $(&$a),*);
    };
}

#[fastout]
fn main() {
    input! {
        n: usize, m: usize,
        a: [Usize1; m],
    }

    let mut ans = vec![m; n];

    for ai in a {
        ans[ai] -= 1;
    }

    println!("{}", ans.iter().join("\n"));
}
