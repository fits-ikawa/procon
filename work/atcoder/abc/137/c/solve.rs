#[allow(unused_macros)]
macro_rules! debug {
    ($($a:expr),* $(,)*) => {
        #[cfg(debug_assertions)]
        eprintln!(concat!($("| ", stringify!($a), "={:?} "),*, "|"), $(&$a),*);
    };
}

#[fastout]
fn main() {
    input! {
        n: usize,
        s: [Chars; n],
    }

    let cnt = s
        .into_iter()
        .map(|si| si.into_iter().sorted().collect::<String>())
        .counts();

    let mut ans = 0;

    for (_, v) in cnt {
        ans += v * (v - 1) / 2;
    }

    println!("{}", ans);
}
