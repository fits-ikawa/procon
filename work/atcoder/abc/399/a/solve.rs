#[allow(unused_macros)]
macro_rules! debug {
    ($($a:expr),* $(,)*) => {
        #[cfg(debug_assertions)]
        eprintln!(concat!($("| ", stringify!($a), "={:?} "),*, "|"), $(&$a),*);
    };
}

#[fastout]
fn main() {
    input! {
        n: usize,
        s: Chars,
        t: Chars,
    }

    let mut cnt = 0;

    for i in 0..n {
        if s[i] != t[i] {
            cnt += 1;
        }
    }

    println!("{}", cnt);
}
