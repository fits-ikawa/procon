#[allow(unused_macros)]
macro_rules! debug {
    ($($a:expr),* $(,)*) => {
        #[cfg(debug_assertions)]
        eprintln!(concat!($("| ", stringify!($a), "={:?} "),*, "|"), $(&$a),*);
    };
}

#[fastout]
fn main() {
    input! {
        w: usize, h: usize, x: usize, y: usize,
    }

    let center = w == x * 2 && h == y * 2;

    println!(
        "{} {}",
        (w as f64 * h as f64) / 2.0,
        if center { 1 } else { 0 }
    );
}
