#[allow(unused_macros)]
macro_rules! debug {
    ($($a:expr),* $(,)*) => {
        #[cfg(debug_assertions)]
        eprintln!(concat!($("| ", stringify!($a), "={:?} "),*, "|"), $(&$a),*);
    };
}

#[fastout]
fn main() {
    input! {
        n: usize,
        mut c: [usize; n],
    }

    c.sort();

    use ac_library::ModInt1000000007 as Mint;

    let mut ans = Mint::new(1);

    for i in 0..n {
        ans *= c[i].saturating_sub(i);
    }

    println!("{}", ans);
}
