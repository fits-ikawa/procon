use superslice::*;

#[allow(unused_macros)]
macro_rules! debug {
    ($($a:expr),* $(,)*) => {
        #[cfg(debug_assertions)]
        eprintln!(concat!($("| ", stringify!($a), "={:?} "),*, "|"), $(&$a),*);
    };
}

#[fastout]
fn main() {
    input! {
        n: usize,
        p: [usize; n],
    }

    let mut mn = usize::MAX;
    let mut ans = 0;

    for pi in p {
        if pi < mn {
            mn = pi;
            ans += 1;
        }
    }

    println!("{}", ans);
}
