#[allow(unused_macros)]
macro_rules! debug {
    ($($a:expr),* $(,)*) => {
        #[cfg(debug_assertions)]
        eprintln!(concat!($("| ", stringify!($a), "={:?} "),*, "|"), $(&$a),*);
    };
}

#[fastout]
fn main() {
    input! {
        n: usize, q: usize,
        lr: [(usize, usize); q],
    }

    let mut uf = ac_library::Dsu::new(n + 1);

    for (l, r) in lr {
        uf.merge(l - 1, r);
    }

    let ans = uf.same(0, n);

    println!("{}", if ans { "Yes" } else { "No" });
}
