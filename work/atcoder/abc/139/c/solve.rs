use itertools::*;
use itertools_num::*;
use maplit::*;
use num::integer::{Integer, Roots};
use proconio::{marker::*, *};
use std::cmp::{Ordering::*, Reverse};
use std::collections::*;
use superslice::*;

#[allow(unused_macros)]
macro_rules! debug {
    ($($a:expr),* $(,)*) => {
        #[cfg(debug_assertions)]
        eprintln!(concat!($("| ", stringify!($a), "={:?} "),*, "|"), $(&$a),*);
    };
}

#[fastout]
fn main() {
    input! {
        n: usize,
        h: [usize; n],
    }

    let mut len = 0;
    let mut ans = 0;

    for i in 0..n - 1 {
        if h[i] >= h[i + 1] {
            len += 1;
            ans = ans.max(len);
        } else {
            len = 0;
        }
    }

    println!("{}", ans);
}
