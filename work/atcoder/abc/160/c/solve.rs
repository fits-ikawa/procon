#[allow(unused_macros)]
macro_rules! debug {
    ($($a:expr),* $(,)*) => {
        #[cfg(debug_assertions)]
        eprintln!(concat!($("| ", stringify!($a), "={:?} "),*, "|"), $(&$a),*);
    };
}

#[fastout]
fn main() {
    input! {
        k: usize, n: usize,
        a: [usize; n],
    }

    let mut ans = k - (k - a[n - 1] + a[0]);

    for (a, b) in a.iter().tuple_windows() {
        ans = ans.min(k - (b - a));
    }

    println!("{}", ans);
}
