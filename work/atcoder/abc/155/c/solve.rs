use itertools::*;
use itertools_num::*;
use maplit::*;
use num::integer::{Integer, Roots};
use proconio::{marker::*, *};
use std::cmp::{Ordering::*, Reverse};
use std::collections::*;
use superslice::*;

#[allow(unused_macros)]
macro_rules! debug {
    ($($a:expr),* $(,)*) => {
        #[cfg(debug_assertions)]
        eprintln!(concat!($("| ", stringify!($a), "={:?} "),*, "|"), $(&$a),*);
    };
}

#[fastout]
fn main() {
    input! {
        n: usize,
        s: [String; n],
    }

    let cnt = s.into_iter().counts();
    let max_cnt = cnt.iter().map(|(_, &c)| c).max().unwrap();

    for si in cnt.keys().sorted() {
        if cnt[si] == max_cnt {
            println!("{}", si);
        }
    }
}
