#[allow(unused_macros)]
macro_rules! debug {
    ($($a:expr),* $(,)*) => {
        #[cfg(debug_assertions)]
        eprintln!(concat!($("| ", stringify!($a), "={:?} "),*, "|"), $(&$a),*);
    };
}

#[fastout]
fn main() {
    input! {
        a: [usize; 3],
    }

    if a[0] == a[1] * a[2] || a[1] == a[0] * a[2] || a[2] == a[0] * a[1] {
        println!("Yes");
        return;
    }

    println!("No");
}
