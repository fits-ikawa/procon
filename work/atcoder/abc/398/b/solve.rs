#[allow(unused_macros)]
macro_rules! debug {
    ($($a:expr),* $(,)*) => {
        #[cfg(debug_assertions)]
        eprintln!(concat!($("| ", stringify!($a), "={:?} "),*, "|"), $(&$a),*);
    };
}

#[fastout]
fn main() {
    input! {
        a: [usize; 7],
    }

    for comb in a.iter().combinations(5) {
        let cnt = comb.iter().counts();

        if cnt.values().sorted().copied().collect_vec() == vec![2, 3] {
            println!("Yes");
            return;
        }
    }

    println!("No");
}
