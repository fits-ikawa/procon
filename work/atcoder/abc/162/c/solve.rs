use superslice::*;

#[allow(unused_macros)]
macro_rules! debug {
    ($($a:expr),* $(,)*) => {
        #[cfg(debug_assertions)]
        eprintln!(concat!($("| ", stringify!($a), "={:?} "),*, "|"), $(&$a),*);
    };
}

#[fastout]
fn main() {
    input! {
        k: usize,
    }

    let mut ans = 0;

    for a in 1..=k {
        for b in 1..=k {
            let ab = a.gcd(&b);
            for c in 1..=k {
                ans += ab.gcd(&c);
            }
        }
    }

    println!("{}", ans);
}
