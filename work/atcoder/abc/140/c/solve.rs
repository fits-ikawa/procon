#![allow(unused_imports)]
use itertools::*;
use itertools_num::*;
use maplit::*;
use num::integer::{Integer, Roots};
use proconio::{marker::*, *};
use std::cmp::{Ordering::*, Reverse};
use std::collections::*;
use superslice::*;

#[allow(unused_macros)]
macro_rules! debug {
    ($($a:expr),* $(,)*) => {
        #[cfg(debug_assertions)]
        eprintln!(concat!($("| ", stringify!($a), "={:?} "),*, "|"), $(&$a),*);
    };
}

#[fastout]
fn main() {
    input! {
        n: usize,
        b: [usize; n-1],
    }

    let mut a = vec![b[0]];

    for i in 0..n - 2 {
        a.push(b[i].min(b[i + 1]));
    }

    a.push(b.last().copied().unwrap());

    println!("{}", a.iter().sum::<usize>());
}
