#![allow(unused_imports)]
use hashbag::HashBag;
use itertools::*;
use itertools_num::*;
use maplit::*;
use num::integer::{Integer, Roots};
use proconio::{marker::*, *};
use std::cmp::{Ordering::*, Reverse};
use std::collections::*;
use superslice::*;

#[allow(unused_macros)]
macro_rules! debug {
    ($($a:expr),* $(,)*) => {
        #[cfg(debug_assertions)]
        eprintln!(concat!($("| ", stringify!($a), "={:?} "),*, "|"), $(&$a),*);
    };
}

#[fastout]
fn main() {
    input! {
        n: usize,
        a: [usize; n],
    }

    let mut left = HashBag::new();
    let mut right = a.iter().copied().collect::<HashBag<_>>();

    let mut ans = 0;

    for i in 0..n - 1 {
        left.insert(a[i]);
        right.remove(&a[i]);

        ans = ans.max(left.set_len() + right.set_len());
    }

    println!("{}", ans);
}
